/**
 * Vendor communications. VendorIQ decides what to say; delivery goes through n8n (Gmail, waits,
 * reminders, escalation). If n8n is not configured, rejects the handoff, or never confirms delivery,
 * the message is sent directly over SMTP so a vendor is never left without an answer.
 */

export type CommKind = "information_request" | "reminder" | "approval_notice" | "review_alert" | "reviewer_request" | "intake_ack" | "manual_message";

export interface Communication {
  id: string;
  application_id: string;
  run_id: string | null;
  kind: CommKind;
  to_email: string;
  subject: string;
  body: string;
  status: "queued" | "sent" | "failed" | "not_configured";
  channel: string;
  created_at: string;
  sent_at: string | null;
  meta: Record<string, unknown> | null;
}

/** EMAIL_PAUSED=1 stops every outgoing email (n8n and SMTP); messages are recorded but not delivered. */
const paused = () => /^(1|true|yes)$/i.test(process.env.EMAIL_PAUSED ?? "");
export const n8nConfigured = () => !paused() && !!process.env.N8N_WEBHOOK_URL;
export const smtpConfigured = () => !paused() && !!(process.env.SMTP_USER && process.env.SMTP_PASS);

/** Subject tag that lets inbound replies find their application. */
export const ref = (appId: string) => `[${appId}]`;
export const REF_RE = /\[(VEN-\d{4}-\d{5})\]/;

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function shell(title: string, inner: string) {
  return `<div style="font-family:Segoe UI,Arial,sans-serif;max-width:600px;margin:0 auto;color:#161616">
  <div style="background:#161616;color:#fff;padding:16px 24px;border-radius:2px 2px 0 0">
    <div style="font-size:13px;opacity:.7">${esc(BUYER.name)} · Vendor Onboarding</div>
    <div style="font-size:18px;font-weight:600;margin-top:2px">${esc(title)}</div>
  </div>
  <div style="border:1px solid #e0e0e0;border-top:0;padding:24px;border-radius:0 0 2px 2px;line-height:1.55;font-size:14px">${inner}
  <p style="margin-top:24px;color:#6f6f6f;font-size:12px">This message was generated by VendorIQ on behalf of the ${esc(BUYER.team)}. You can reply to this email directly - attachments you send are added to your application.</p>
  </div></div>`;
}

function itemsHtml(items: RequestedItem[]) {
  return `<ol style="padding-left:18px">${items
    .map(
      (i) => `<li style="margin-bottom:10px"><strong>${esc(i.title)}</strong><br/><span style="color:#525252">${esc(i.instruction)}</span>${
        i.suggested_value ? `<br/><span style="color:#0043ce">Suggested value from your documents: <code>${esc(i.suggested_value)}</code></span>` : ""
      }</li>`,
    )
    .join("")}</ol>`;
}

const button = (url: string, label: string) =>
  `<p style="margin:22px 0"><a href="${url}" style="background:#0f62fe;color:#fff;padding:11px 20px;border-radius:2px;text-decoration:none;font-weight:600">${esc(label)}</a></p>`;

export async function composeInformationRequest(app: Application, items: RequestedItem[], appUrl: string, reminderNo = 0) {
  const link = `${appUrl}/vendor/${app.resubmit_token}`;
  const confirming = items.some((i) => i.kind === "confirm");
  const subject = reminderNo
    ? `Reminder ${reminderNo}: action still needed on your vendor registration ${ref(app.id)}`
    : `Action needed: complete your vendor registration with ${BUYER.name} ${ref(app.id)}`;
  const ai = await aiIntro({ vendor: app.legal_name, contact: app.contact_name, buyer: BUYER.name, items, reminderNo, channel: app.source });
  const fallback = reminderNo
    ? `We are still waiting for the items below before we can complete the verification of <strong>${esc(app.legal_name)}</strong>. Your application stays on hold until they are received.`
    : confirming
      ? `Thank you for sending your documents for <strong>${esc(app.legal_name)}</strong>. We have read them and pre-filled your registration - please check it and complete the items below.`
      : `Thank you for registering <strong>${esc(app.legal_name)}</strong> as a supplier to ${esc(BUYER.name)}. We reviewed your submission and need the following before we can continue:`;
  const html = shell(
    reminderNo ? "Reminder - information still required" : confirming ? "Please confirm your details" : "Additional information required",
    `<p>Hello ${esc(app.contact_name || "there")},</p><p>${ai ? esc(ai) : fallback}</p>${itemsHtml(items)}${button(link, confirming ? "Review and confirm" : "Update my application")}<p style="color:#525252">Or simply reply to this email with the documents attached. Your application reference is <strong>${app.id}</strong>.</p>`,
  );
  const text = `${subject}\n\n${items.map((i, n) => `${n + 1}. ${i.title}: ${i.instruction}`).join("\n")}\n\nUpdate your application: ${link}`;
  return { subject, html, text, link, ai_worded: !!ai };
}

/** A message written by a person on the team. Their words are sent as typed (escaped), signed with their name. */
export function composeManualMessage(app: Application, opts: { subject: string; message: string; includeLink: boolean; sender: string }, appUrl: string) {
  const subject = REF_RE.test(opts.subject) ? opts.subject : `${opts.subject.trim()} ${ref(app.id)}`;
  const link = `${appUrl}/vendor/${app.resubmit_token}`;
  const paragraphs = opts.message.trim().split(/\n{2,}/).map((p) => `<p>${esc(p).replace(/\n/g, "<br/>")}</p>`).join("");
  const html = shell(
    `Message about your registration`,
    `<p>Hello ${esc(app.contact_name || "there")},</p>${paragraphs}${opts.includeLink ? button(link, "Open my application") : ""}<p>Regards,<br/>${esc(opts.sender)}<br/><span style="color:#6f6f6f">${esc(BUYER.team)}, ${esc(BUYER.name)}</span></p><p style="color:#525252">Your application reference is <strong>${app.id}</strong>.</p>`,
  );
  const text = [`Hello ${app.contact_name || "there"},`, opts.message.trim(), opts.includeLink ? `Open your application: ${link}` : "", `Regards,\n${opts.sender}\n${BUYER.team}, ${BUYER.name}`]
    .filter(Boolean).join("\n\n");
  return { subject, html, text, ai_worded: false };
}

export function composeApproval(app: Application, decision: Decision) {
  const subject = `Your vendor registration with ${BUYER.name} is approved ${ref(app.id)}`;
  const msme = decision.conditions.some((c) => c.startsWith("MSME"));
  const html = shell(
    "Vendor registration approved",
    `<p>Hello ${esc(app.contact_name || "there")},</p><p>We're pleased to confirm that <strong>${esc(app.legal_name)}</strong> has been approved as a supplier to ${esc(BUYER.name)}.</p>${
      decision.conditions.some((c) => /bank/i.test(c)) ? `<p>Before the first payment, our finance team will confirm your bank account details with you. No action is needed right now.</p>` : ""
    }${msme ? `<p>We have recorded your MSME registration; payment terms will follow the MSMED Act.</p>` : ""}<p>Reference: <strong>${app.id}</strong></p>`,
  );
  return { subject, html, text: `${subject}\n\nReference ${app.id}.`, ai_worded: false };
}

export function composeReviewAlert(app: Application, decision: Decision, appUrl: string) {
  const subject = `[Review needed] ${app.legal_name} - ${decision.reasons.length} discrepancy(ies) ${ref(app.id)}`;
  const html = shell(
    "Vendor application needs review",
    `<p><strong>${esc(app.legal_name)}</strong> (${app.id}) was routed to manual review.</p>${
      decision.ai_brief ? `<p style="background:#f1f5f9;padding:10px 12px;border-radius:8px">${esc(decision.ai_brief.summary)}</p>` : ""
    }<ul>${decision.reasons.map((r) => `<li style="margin-bottom:6px">${esc(r.text)}</li>`).join("")}</ul>${button(`${appUrl}/applications/${app.id}`, "Open in VendorIQ")}`,
  );
  return { subject, html, text: `${subject}\n\n${decision.reasons.map((r) => `- ${r.text}`).join("\n")}`, ai_worded: false };
}

// ---- delivery ----------------------------------------------------------------------------------

let transport: Transporter | null = null;

async function sendSmtp(to: string, subject: string, html: string, text: string) {
  transport ??= nodemailer.createTransport({
    host: process.env.SMTP_HOST ?? "smtp.gmail.com",
    port: Number(process.env.SMTP_PORT ?? 465),
    secure: Number(process.env.SMTP_PORT ?? 465) === 465,
    auth: { user: process.env.SMTP_USER, pass: (process.env.SMTP_PASS ?? "").replace(/\s/g, "") },
  });
  const info = await transport.sendMail({
    from: process.env.SMTP_FROM ?? `${BUYER.name} Vendor Onboarding <${process.env.SMTP_USER}>`,
    to, subject, html, text,
  });
  return info.messageId as string;
}

/** Automated mail (bounces, newsletters, out-of-office, no-reply senders) never gets an automatic answer. */
export function isAutomatedEmail(from: string, subject: string) {
  return /(no-?reply|mailer-daemon|postmaster|notifications?@|bounce)/i.test(from)
    || /(delivery status notification|undeliverable|returned mail|auto(matic)?[- ]?reply|out of (the )?office)/i.test(subject);
}

/**
 * A vendor emailed the onboarding inbox but nothing usable was attached: tell them what to send instead of
 * staying silent. Sent directly over SMTP (there is no application to attach it to yet).
 */
export async function sendDocumentsHelp(to: string, originalSubject: string, ignored: string[], portalUrl: string) {
  if (!smtpConfigured()) return false;
  const subject = /^re:/i.test(originalSubject) ? originalSubject : `Re: ${originalSubject || "Supplier registration"}`;
  const docs = ["GST registration certificate", "PAN card of the business", "Cancelled cheque or bank letter",
    "Certificate of Incorporation (companies and LLPs only)", "Udyam certificate (only if you are a registered MSME)"];
  const got = ignored.length
    ? `<p>We received ${ignored.map((n) => `<strong>${esc(n)}</strong>`).join(", ")}, but ${ignored.length === 1 ? "it does not look like" : "they do not look like"} a registration document.</p>`
    : `<p>We could not find any documents attached to your email.</p>`;
  const html = shell("Please attach your registration documents",
    `<p>Hello,</p><p>Thank you for writing to ${esc(BUYER.name)} about supplier registration.</p>${got}
     <p>Please reply to this email with these documents <strong>attached as files</strong> (PDF, PNG or JPG - not links):</p>
     <ul>${docs.map((d) => `<li>${esc(d)}</li>`).join("")}</ul>
     <p>Prefer a form? You can also register online:</p>${button(portalUrl, "Register online")}`);
  const text = [
    `Thank you for writing to ${BUYER.name} about supplier registration.`,
    ignored.length ? `We received ${ignored.join(", ")}, but it does not look like a registration document.` : "We could not find any documents attached to your email.",
    `Please reply with these documents attached as files:\n- ${docs.join("\n- ")}`,
    `Or register online: ${portalUrl}`,
  ].join("\n\n");
  await sendSmtp(to, subject, html, text);
  return true;
}

export async function smtpFallback(id: string, reason: string) {
  const c = await one<Communication>("select * from communications where id=$1", [id]);
  if (!c) return;
  const to = (c.meta?.delivered_to as string) || c.to_email;
  if (!smtpConfigured()) {
    await query(`update communications set status=$2, meta = coalesce(meta,'{}'::jsonb) || $3::jsonb where id=$1`, [
      id, n8nConfigured() ? "failed" : "not_configured", json({ fallback_reason: reason, smtp: "not configured" }),
    ]);
    return;
  }
  // Claim it first: overlapping watchdog pings or a late n8n callback must never send the same email twice.
  const claimed = await one<{ id: string }>(
    `update communications set meta = coalesce(meta,'{}'::jsonb) || '{"smtp_claimed": true}'::jsonb
      where id=$1 and status='queued' and not (coalesce(meta,'{}'::jsonb) ? 'smtp_claimed') returning id`, [id],
  );
  if (!claimed) return;
  try {
    const messageId = await sendSmtp(to, c.subject, c.body, (c.meta?.text as string) ?? c.subject);
    await query(
      `update communications set status='sent', channel='smtp', sent_at=now(), meta = coalesce(meta,'{}'::jsonb) || $2::jsonb where id=$1`,
      [id, json({ message_id: messageId, fallback_reason: reason, reminders_paused: !!c.meta?.reminders })],
    );
    await query(`insert into audit_log (application_id, actor, action, detail) values ($1,'system','email_sent',$2::jsonb)`, [
      c.application_id, json({ communication_id: id, kind: c.kind, subject: c.subject, channel: "smtp", reason }),
    ]);
  } catch (err) {
    await query(`update communications set status='failed', meta = coalesce(meta,'{}'::jsonb) || $2::jsonb where id=$1`, [
      id, json({ error: (err as Error).message, fallback_reason: reason }),
    ]);
  }
}

/** Records the communication and hands it to n8n (or SMTP when n8n is unavailable). */
export async function dispatch(opts: {
  app: Application;
  runId: string | null;
  kind: CommKind;
  to: string;
  content: { subject: string; html: string; text: string; ai_worded?: boolean };
  appUrl: string;
  reminders: boolean;
  meta?: Record<string, unknown>;
}): Promise<Communication> {
  const id = `COM-${randomUUID().slice(0, 8).toUpperCase()}`;
  const deliverTo = process.env.EMAIL_OVERRIDE_TO || opts.to;
  const meta = {
    ...opts.meta, intended_to: opts.to, delivered_to: deliverTo, text: opts.content.text,
    ai_worded: !!opts.content.ai_worded, reminders: opts.reminders ? COMMS : null,
  };
  await query(
    `insert into communications (id, application_id, run_id, kind, to_email, subject, body, status, channel, meta)
     values ($1,$2,$3,$4,$5,$6,$7,'queued','n8n',$8::jsonb)`,
    [id, opts.app.id, opts.runId, opts.kind, opts.to, opts.content.subject, opts.content.html, json(meta)],
  );

  if ((opts.app.intake_meta as { quiet?: boolean } | null)?.quiet) {
    // Imported history: keep the record of what would have been sent, but do not email anyone.
    await query(`update communications set status='not_configured', meta = coalesce(meta,'{}'::jsonb) || $2::jsonb where id=$1`, [
      id, json({ suppressed: "Imported vendor history - not emailed" }),
    ]);
  } else if (!n8nConfigured()) {
    await smtpFallback(id, "n8n not configured");
  } else {
    try {
      const res = await fetch(process.env.N8N_WEBHOOK_URL!, {
        method: "POST",
        headers: { "content-type": "application/json", "x-vendoriq-secret": process.env.N8N_SHARED_SECRET ?? "" },
        body: JSON.stringify({
          event: "vendor_communication",
          communication_id: id,
          application_id: opts.app.id,
          vendor_name: opts.app.legal_name,
          kind: opts.kind,
          to: deliverTo,
          intended_to: opts.to,
          subject: opts.content.subject,
          html: opts.content.html,
          text: opts.content.text,
          reminders: opts.reminders
            ? { enabled: true, after_minutes: COMMS.reminderAfterMinutes, max: COMMS.maxReminders }
            : { enabled: false, after_minutes: 0, max: 0 },
          status_url: `${opts.appUrl}/api/n8n/status/${id}`,
          callback_url: `${opts.appUrl}/api/n8n/callback`,
        }),
        signal: AbortSignal.timeout(30_000),
      });
      if (!res.ok) throw new Error(`n8n responded ${res.status}`);
    } catch (err) {
      const e = err as Error;
      if (e.name === "TimeoutError") {
        // n8n may still deliver it (a free instance can be slow). Sending now could duplicate the email,
        // so leave it queued: the watchdog sends it over SMTP if n8n never confirms delivery.
        await query(`update communications set meta = coalesce(meta,'{}'::jsonb) || $2::jsonb where id=$1`, [
          id, json({ handoff: "n8n slow to acknowledge - watchdog will use SMTP if delivery is not confirmed" }),
        ]);
      } else {
        await smtpFallback(id, `n8n handoff failed: ${e.message}`);
      }
    }
  }
  return (await one<Communication>("select * from communications where id=$1", [id]))!;
}

/**
 * Watchdog: n8n accepted a message but never reported delivery. Called from /api/health (pinged every
 * few minutes) so stuck messages go out over SMTP instead of silently waiting.
 */
export async function sweepUndelivered(maxAgeMinutes = 3) {
  const stuck = await query<{ id: string }>(
    `select id from communications where status='queued' and channel='n8n' and created_at < now() - ($1 || ' minutes')::interval`,
    [String(maxAgeMinutes)],
  );
  for (const s of stuck) await smtpFallback(s.id, `n8n did not confirm delivery within ${maxAgeMinutes} minutes`);
  return stuck.length;
}

export function describeDelivery(c: Communication, to: string) {
  if (c.status === "queued") return { level: "success" as const, text: `handed to n8n → ${to}` };
  if (c.status === "sent") return { level: "success" as const, text: `sent directly over SMTP → ${to} (${String(c.meta?.fallback_reason ?? "backup")})` };
  if (c.status === "not_configured") return { level: "warning" as const, text: "drafted only - email sending is paused or not configured" };
  return { level: "error" as const, text: `delivery failed (${String(c.meta?.error ?? c.meta?.fallback_reason ?? "unknown")})` };
}
